import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { PUBLIC_RUNTIME_SURFACE } from '../lib/publicRuntimeSurface.mjs';
import { readAuthoredPageRegistry } from '../docs-quality/pageRegistrySource.mjs';
import { buildReferenceManifest } from './buildReferenceManifest.mjs';

const repositoryRoot = resolve(import.meta.dirname, '../..');

function readCoreDocSources() {
  const bridge = resolve(repositoryRoot, 'packages/core/scripts/read-doc-sources.mjs');
  const result = spawnSync(process.execPath, [bridge], {
    cwd: repositoryRoot,
    encoding: 'utf8',
  });
  if (result.status !== 0) {
    throw new Error(`Core documentation source bridge failed: ${result.stderr.trim()}`);
  }
  return JSON.parse(result.stdout);
}

function read(relativePath) {
  return readFileSync(resolve(repositoryRoot, relativePath), 'utf8');
}

function readJson(relativePath) {
  return JSON.parse(read(relativePath));
}

const packages = Object.freeze({
  core: 'index.ts',
  react: 'index.ts',
  'creator-core': 'index.ts',
  'creator-react': 'index.tsx',
  themes: 'index.ts',
});
const packageIndexSources = Object.fromEntries(Object.entries(packages).map(([name, entry]) => {
  const packageName = readJson(`packages/${name}/package.json`).name;
  return [packageName, read(`packages/${name}/src/${entry}`)];
}));
const coreDocSources = readCoreDocSources();

const manifest = buildReferenceManifest({
  metadata: readJson('contracts/runtime-metadata.json'),
  schema: readJson('contracts/survey-schema.json'),
  diagnostics: readJson('contracts/runtime-diagnostics.json'),
  expressionConformance: readJson('conformance/v1/expressions.json'),
  operatorSource: coreDocSources.operatorSource,
  functionSource: coreDocSources.functionSource,
  publicInterfaceLedger: read('docs/public-package-interfaces.md'),
  packageIndexSources,
  publicRuntimeSurface: PUBLIC_RUNTIME_SURFACE,
});

const referenceOutput = [
  '// Generated by scripts/docs/generate-reference-manifest.mjs. Do not edit by hand.',
  "import type { DocsReferenceManifest } from '../docsReferenceTypes.js';",
  '',
  `export const docsReferenceManifest = ${JSON.stringify(manifest)} as const satisfies DocsReferenceManifest;`,
  '',
].join('\n');

const authoredPages = readAuthoredPageRegistry(repositoryRoot)
  .toSorted((left, right) => left.slug.localeCompare(right.slug))
  .map((page) => {
    if (page.title === undefined || page.description === undefined) {
      throw new Error(`Authored documentation metadata is incomplete for "${page.slug}".`);
    }
    return {
      id: page.slug === '' ? 'home' : page.slug,
      title: page.title,
      description: page.description,
      url: page.slug === '' ? '/docs' : `/docs/${page.slug}`,
      headings: page.toc.map((item) => item.label).filter((label) => label !== undefined),
      keywords: [page.slug, page.section, page.audience, page.sdk, page.framework]
        .filter((value) => value !== undefined),
    };
  });
const authoredOutput = [
  '// Generated by scripts/docs/generate-reference-manifest.mjs. Do not edit by hand.',
  "import type { AuthoredPageSearchRecord } from '../documentationSearch.js';",
  '',
  `export const authoredDocsManifest = ${JSON.stringify(authoredPages)} as const satisfies readonly AuthoredPageSearchRecord[];`,
  '',
].join('\n');

/**
 * The sitemap, from the same pages the manifests were just built from — checklist P13.
 *
 * **Generated, because a hand-kept list is wrong the day somebody adds a page**, and most
 * of this site's pages were never written by hand at all: the reference is a page per
 * definition type, generated from the metadata registry. A list maintained beside it would
 * be a second copy of what this script already knows, and the two would part company
 * silently.
 *
 * Written here rather than by the framework's own sitemap option, which would mean the Vite
 * config importing application source — and the site's project resolves modules as a
 * bundler does while the config is type-checked as Node does, so the two would fight over
 * which files they own. Emitting it here also makes it a **committed artifact with a drift
 * check**, exactly like `contracts/`: `check:docs` already fails when a generated file and
 * its source disagree, so the sitemap inherits that for nothing.
 *
 * Priority is a hint about *relative* importance within one site, and the honest ranking is
 * that somebody arriving from a search wants the thing they can try or the thing that
 * explains it, not the reference page for a validator property.
 */
const SITE_ORIGIN = 'https://kajay.io';
const sitemapEntries = [
  { path: '/', priority: '1.0', changefreq: 'weekly' },
  { path: '/playground', priority: '0.9', changefreq: 'weekly' },
  ...[...authoredPages.map((page) => page.url), ...Object.values(manifest).flatMap((group) => (Array.isArray(group) ? group : [])).map((fact) => fact.url)]
    .filter((url) => typeof url === 'string' && url.startsWith('/'))
    .filter((url, at, all) => all.indexOf(url) === at && url !== '/' && url !== '/playground')
    .map((url) => ({ path: url, priority: '0.5', changefreq: 'monthly' })),
];
const sitemapOutput = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...sitemapEntries.map((entry) =>
    [
      '  <url>',
      `    <loc>${SITE_ORIGIN}${entry.path}</loc>`,
      `    <changefreq>${entry.changefreq}</changefreq>`,
      `    <priority>${entry.priority}</priority>`,
      '  </url>',
    ].join('\n'),
  ),
  '</urlset>',
  '',
].join('\n');

const outputs = [
  ['apps/site/src/features/docs-reference/generated/docsReferenceManifest.ts', referenceOutput],
  ['apps/site/src/features/docs-reference/generated/authoredDocsManifest.ts', authoredOutput],
  ['apps/site/public/sitemap.xml', sitemapOutput],
];

for (const [relativeOutputPath, output] of outputs) {
  const outputPath = resolve(repositoryRoot, relativeOutputPath);
  if (process.argv.includes('--check')) {
    if (readFileSync(outputPath, 'utf8') !== output) {
      throw new Error(`${relativeOutputPath} is stale; regenerate the documentation reference manifest.`);
    }
    console.log(`Checked ${relativeOutputPath}.`);
  } else {
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, output);
    console.log(`Generated ${relativeOutputPath}.`);
  }
}
